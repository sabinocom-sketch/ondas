import {chromium,expect} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const server=await chromium.launchServer({channel:'chrome',headless:true});
try {
 const browser=await chromium.connect(server.wsEndpoint());
 const page=await browser.newPage({hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(resolve('Ondas.html')).href);
 await page.getByRole('button',{name:'Ativar áudio'}).click();
 await page.getByText('Áudio ativo',{exact:true}).waitFor();
 if(await page.locator('.key').count()!==49)throw new Error('Teclado incompleto');
 await page.locator('h1').click();await page.keyboard.down('a');
 if(await page.locator('.pressed').count()!==1)throw new Error('Nota não ativada');
 await page.keyboard.up('a');
 await expect(page.locator('#preset option')).toHaveCount(20);
 await page.getByRole('button',{name:'Piano em ecrã inteiro',exact:true}).click();
 await expect(page.locator('.piano-full')).toBeVisible();
 await page.getByRole('button',{name:'Sair do piano em ecrã inteiro'}).click();
 await expect(page.locator('.piano-full')).toHaveCount(0);
 await page.getByRole('button',{name:'Tocar',exact:true}).click();
 await page.getByRole('button',{name:'Gravar',exact:false}).click();
 await page.keyboard.down('a');
 await expect.poll(()=>page.getByLabel('Duração da gravação').textContent(),{timeout:30000}).not.toBe('00:00');
 await page.keyboard.up('a');await page.getByRole('button',{name:'Parar gravação'}).click();
 const data=await page.getByRole('link',{name:'Descarregar WAV'}).evaluate(async el=>{const b=await(await fetch(el.href)).arrayBuffer();const v=new DataView(b);let peak=0;for(let i=44;i<b.byteLength;i+=2)peak=Math.max(peak,Math.abs(v.getInt16(i,true)));return {size:b.byteLength,peak,channels:v.getUint16(22,true)}});
 if(data.size<=44||data.peak===0||data.channels!==2)throw new Error('WAV inválido ou silencioso');
 await page.getByRole('button',{name:'Compor',exact:true}).click();
 await page.getByRole('button',{name:'Adicionar nota',exact:true}).click();
 await page.getByLabel('Duração da nota',{exact:true}).fill('32');
 await page.getByRole('button',{name:'Gravar',exact:false}).click();
 await page.getByRole('button',{name:'Reproduzir composição'}).click();
 await expect(page.getByRole('button',{name:'Parar composição'})).toBeVisible();
 await expect.poll(()=>page.getByLabel('Duração da gravação').textContent(),{timeout:30000}).not.toBe('00:00');
 await page.getByRole('button',{name:'Parar composição'}).click();
 await page.getByRole('button',{name:'Parar gravação'}).click();
 const compositionPeak=await page.getByRole('link',{name:'Descarregar WAV'}).evaluate(async el=>{const b=await(await fetch(el.href)).arrayBuffer(),v=new DataView(b);let peak=0;for(let i=44;i<b.byteLength;i+=2)peak=Math.max(peak,Math.abs(v.getInt16(i,true)));return peak});
 if(compositionPeak===0)throw new Error('Composição silenciosa');
 await page.getByRole('button',{name:'Limpar composição',exact:true}).click();
 await page.getByRole('button',{name:'Ir para a bateria',exact:true}).click();
 const drum=page.getByRole('button',{name:'Bombo, passo 1',exact:true});await drum.tap();await expect(drum).toHaveAttribute('data-velocity','0.65');
 await page.getByLabel('Ritmo de bateria',{exact:true}).selectOption('house');
 await page.getByRole('button',{name:'Gravar',exact:false}).click();await page.getByRole('button',{name:'Reproduzir bateria + piano',exact:false}).click();
 await expect.poll(()=>page.getByLabel('Duração da gravação').textContent(),{timeout:30000}).not.toBe('00:00');
 await page.getByRole('button',{name:'Parar bateria + piano',exact:false}).click();await page.getByRole('button',{name:'Parar gravação'}).click();
 const drumPeak=await page.getByRole('link',{name:'Descarregar WAV'}).evaluate(async el=>{const b=await(await fetch(el.href)).arrayBuffer(),v=new DataView(b);let peak=0;for(let i=44;i<b.byteLength;i+=2)peak=Math.max(peak,Math.abs(v.getInt16(i,true)));return peak});
 if(drumPeak===0)throw new Error('Bateria silenciosa');
 const studio=page.getByRole('region',{name:'Estúdio multipistas'});
 await studio.getByRole('button',{name:'Nova pista'}).click();await page.getByRole('button',{name:'Reproduzir bateria + piano',exact:false}).click();
 await expect.poll(()=>studio.getByLabel('Tempo multipistas').textContent(),{timeout:30000}).not.toContain('00:00');
 await page.getByRole('button',{name:'Parar bateria + piano',exact:false}).click();await studio.getByRole('button',{name:'Parar pistas'}).click();
 await expect(studio.locator('.audio-track')).toHaveCount(1);await studio.getByRole('button',{name:'Preparar mistura WAV'}).click();await expect(studio.getByRole('link',{name:'Descarregar mistura'})).toBeVisible({timeout:30000});
 const multiPeak=await studio.getByRole('link',{name:'Descarregar mistura'}).evaluate(async el=>{const v=new DataView(await(await fetch(el.href)).arrayBuffer());let peak=0;for(let i=44;i<v.byteLength;i+=2)peak=Math.max(peak,Math.abs(v.getInt16(i,true)));return peak});if(!multiPeak)throw new Error('Mistura multipistas silenciosa');
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS: HTML local, 49 teclas, modo Tocar, áudio ativo, gravação WAV estéreo com sinal piano roll e bateria com sinal, incluindo toque na grelha e mistura multipistas, sem erros.');
} finally {await server.kill();}
